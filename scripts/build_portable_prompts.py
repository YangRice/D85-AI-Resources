#!/usr/bin/env python3
"""Build self-contained copy/paste prompts from the canonical skill catalog.

Generates two versions per skill:
  - <skill-id>.en.md  — English (always, from SKILL.md)
  - <skill-id>.zh.md  — Chinese (only if SKILL.zh.md exists in the skill dir)
"""

from __future__ import annotations

import json
import re
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
CATALOG = json.loads((ROOT / "catalog" / "skills.json").read_text(encoding="utf-8"))
INTEGRATIONS = json.loads(
    (ROOT / "catalog" / "integrations.json").read_text(encoding="utf-8")
)["actions"]
OUT_DIR = ROOT / "prompts"
FRONTMATTER_RE = re.compile(r"^---\n.*?\n---\n", re.DOTALL)
ACTION_RE = re.compile(r"`action:([a-z0-9-]+)`")

LANG = {
    "en": {
        "header": "Universal AI Guide",
        "generated": "Generated from the canonical skill catalog and `SKILL.md` packages.",
        "edit_warn": "Do not edit this file manually.",
        "note": "Portable text edition. Copy the section from **Instructions for the AI** through **End of instructions** into a general-purpose AI chat tool.",
        "compat_title": "Compatibility note",
        "compat": "This guide requires text chat only. Links, file uploads, audio, web access, memory, and native skill invocation are optional. State any unavailable capability truthfully and use the manual fallback in the instructions.",
        "instructions": "Instructions for the AI",
        "bundled": "Bundled capability: {}",
        "bundled_note": "Use this capability only when the current journey stage requires it. Do not announce internal composition unless the user asks.",
        "end": "End of instructions",
        "input_label": "Suggested user input",
        "fields": [
            "My goal or assigned role:",
            "My current stage:",
            "Meeting or deadline:",
            "Official project or club instructions I have:",
            "Material I can share:",
            "Preferred response language:",
        ],
        "source": "Source package",
    },
    "zh": {
        "header": "通用 AI 指南",
        "generated": "由规范技能目录和 `SKILL.md` 包生成。",
        "edit_warn": "请勿手动编辑此文件。",
        "note": "便携文本版。将 **AI 指令** 至 **指令结束** 之间的内容复制到通用 AI 聊天工具中使用。",
        "compat_title": "兼容性说明",
        "compat": "本指南只需文字聊天即可使用。链接、文件上传、音频、网页访问、记忆和原生技能调用均为可选功能。若某功能不可用，请如实说明并改用指令中的手动方案。",
        "instructions": "AI 指令",
        "bundled": "内置能力：{}",
        "bundled_note": "仅在当前旅程阶段需要时使用此能力。除非用户询问，否则不要透露内部组合方式。",
        "end": "指令结束",
        "input_label": "建议用户输入格式",
        "fields": [
            "我的目标或角色：",
            "当前阶段：",
            "会议或截止日期：",
            "已有的官方项目或俱乐部说明：",
            "我可以分享的材料：",
            "回复语言偏好：",
        ],
        "source": "来源包",
    },
}

TOOL_FINDER_FIELDS = {
    "en": ["What I want to do next:", "My current stage or meeting role:", "Preferred response language:"],
    "zh": ["我接下来想做什么：", "当前阶段或会议角色：", "回复语言偏好："],
}


def skill_body(skill_id: str, lang: str = "en") -> str | None:
    """Read the skill body for a given language.

    English comes from SKILL.md, other languages from SKILL.<lang>.md.
    Returns None if the file does not exist.
    """
    fname = "SKILL.md" if lang == "en" else f"SKILL.{lang}.md"
    path = ROOT / "skills" / skill_id / fname
    if not path.exists():
        return None
    text = path.read_text(encoding="utf-8")
    return FRONTMATTER_RE.sub("", text, count=1).strip()


def resolve_actions(text: str) -> str:
    def replace(match: re.Match[str]) -> str:
        action_id = match.group(1)
        action = INTEGRATIONS.get(action_id)
        if not action:
            raise ValueError(f"Unknown action in prompt body: {action_id}")
        return f"[{action['label']}]({action['url']})"

    return ACTION_RE.sub(replace, text)


def build_prompt(item: dict, lang: str = "en") -> str | None:
    skill_id = item["id"]
    body = skill_body(skill_id, lang)
    if body is None:
        return None

    meta = LANG[lang]
    dependencies = item.get("requires", []) + item.get("recommends", [])

    sections = [
        f"# {skill_id} — {meta['header']}",
        "",
        f"> {meta['generated']} {meta['edit_warn']}",
        "",
        f"> {meta['note']}",
        "",
        f"## {meta['compat_title']}",
        "",
        meta["compat"],
        "",
        f"## {meta['instructions']}",
        "",
        resolve_actions(body),
    ]

    for dependency in dependencies:
        dep_body = skill_body(dependency, lang)
        if dep_body is None:
            continue
        sections.extend(
            [
                "",
                f"## {meta['bundled'].format(dependency)}",
                "",
                meta["bundled_note"],
                "",
                resolve_actions(dep_body),
            ]
        )

    sections.extend(
        [
            "",
            f"## {meta['end']}",
            "",
            f"## {meta['input_label']}",
            "",
            "```text",
        ]
    )
    sections.extend(TOOL_FINDER_FIELDS[lang] if skill_id == "find-tmcompanion-tool" else meta["fields"])
    sections.extend(
        [
            "```",
            "",
            f"{meta['source']}: `{skill_id}` v{item['version']}",
            "",
        ]
    )

    return "\n".join(sections)


def main() -> None:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for item in CATALOG["skills"]:
        skill_id = item["id"]

        # English — always generated from SKILL.md
        en_out = build_prompt(item, "en")
        en_path = OUT_DIR / f"{skill_id}.en.md"
        en_path.write_text(en_out, encoding="utf-8")
        print(f"{en_path.relative_to(ROOT)}: {len(en_out)} chars")

        # Chinese — only if SKILL.zh.md exists
        zh_out = build_prompt(item, "zh")
        if zh_out:
            zh_path = OUT_DIR / f"{skill_id}.zh.md"
            zh_path.write_text(zh_out, encoding="utf-8")
            print(f"{zh_path.relative_to(ROOT)}: {len(zh_out)} chars")
        else:
            print(f"  ⚠️  {skill_id}: SKILL.zh.md not found, skipping Chinese prompt")


if __name__ == "__main__":
    main()
